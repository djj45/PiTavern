import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import { performance } from "node:perf_hooks";
import type { AgentMessage } from "@earendil-works/pi-agent-core";
import { buildWorkingContext, completeToolGroups, contextChars, contentHash, extractContextFacts } from "../src/context/working-set.ts";
import { compressHistory as baseline } from "./fixtures/compression-v060.ts";
import { assistantMessage, longContextFixture, toolContextFixture, userMessage } from "./context-fixtures.ts";
import { createTokenCounter, measureContext } from "../src/context/tokens.ts";
import { createInitialWorldSnapshot, createWorldTemplateRecord } from "../src/world/index.ts";
import { getWorldTemplate } from "../src/world/catalog.ts";
let checks = 0; const check = (label: string) => { console.log("✓ " + label); checks++; };
const config = { enabled: true, keepFullTurns: 3 };
const comparisons = [100, 500, 1000].map((turns) => {
  const fixture = longContextFixture(turns); const original = JSON.stringify(fixture.messages);
  const start = performance.now(); const old = baseline(fixture.messages, config, 16000); const oldMs = performance.now() - start;
  const nextStart = performance.now(); const next = buildWorkingContext({ messages: fixture.messages, config, budget: 16000 }); const nextMs = performance.now() - nextStart;
  const oldHits = fixture.facts.filter((f) => JSON.stringify(old.messages).includes(f)).length;
  const newHits = fixture.facts.filter((f) => JSON.stringify(next.messages).includes(f)).length;
  assert.equal(newHits, 3); assert.equal(oldHits, 0); assert.ok(contextChars(next.messages) <= 16000);
  assert.equal(JSON.stringify(fixture.messages), original);
  assert.deepEqual(next.messages.slice(-5), fixture.messages.slice(-5));
  assert.deepEqual(buildWorkingContext({ messages: fixture.messages, config, budget: 16000 }), next);
  assert.ok(next.diagnostics.omittedFacts > 0, "有限预算必须报告遗漏");
  return { turns, baseline: { chars: contextChars(old.messages), hits: oldHits, milliseconds: oldMs }, workingSet: { chars: contextChars(next.messages), hits: newHits, milliseconds: nextMs } };
});
check("100/500/1000 回合：同预算末尾事实 0/3 → 3/3，保留最近轮次、纯函数且重建确定");
const fixture = longContextFixture(100);
const built = buildWorkingContext({ messages: fixture.messages, config, budget: 16000 });
for (const fact of built.facts) {
  const m = fixture.messages[fact.source.message];
  const raw = typeof m.content === "string" ? m.content : m.content.filter((b) => b.type === "text").map((b) => b.type === "text" ? b.text : "").join("");
  assert.equal(contentHash(raw), fact.source.hash);
  assert.equal(raw.slice(fact.source.start, fact.source.end), fact.text);
}
check("所有摘录可由消息内容 SHA-256 和原文区间核验");
const tools = toolContextFixture();
const compact = buildWorkingContext({ messages: tools, config: { ...config, keepFullTurns: 1 }, budget: 20000 });
assert.ok(JSON.stringify(compact.messages).includes("码头钟楼的入口在地下"));
assert.ok(compact.facts.some((f) => f.kind === "tool_receipt" && f.tool?.id === "old-call"));
assert.ok(!JSON.stringify(compact.messages).includes('"query":"地图"'), "旧工具参数不重放");
assert.deepEqual(compact.messages.slice(-3), tools.slice(-3)); assert.ok(completeToolGroups(compact.messages));
check("超长已完成工具结果变为结构化回执并保留尾部线索；当前链全文保留");
const split: AgentMessage[] = [...tools.slice(0, 2), { role: "system", content: "深度注入", timestamp: 0 }, ...tools.slice(2)];
const guarded = buildWorkingContext({ messages: split, config: { ...config, keepFullTurns: 1 }, budget: 20000 });
assert.deepEqual(guarded.messages, split); assert.equal(guarded.stats.overBudget, true);
assert.ok(guarded.diagnostics.overBudgetReasons[0].includes("不可拆分"));
check("跨系统消息的工具链与未闭合工具组保持原样，超预算明确拒绝");
const noCompress = buildWorkingContext({ messages: fixture.messages, config: { ...config, enabled: false }, budget: 16000 });
assert.deepEqual(noCompress.messages, fixture.messages); assert.equal(noCompress.stats.triggered, false);
check("关闭压缩保留原上下文，不静默裁切");
const record = createWorldTemplateRecord(getWorldTemplate("tavern-sword"));
const world = createInitialWorldSnapshot(record); world.money[record.template.initial.actorId] = 77;
const worldBefore = JSON.stringify(world);
const withWorld = buildWorkingContext({ messages: [assistantMessage("<summary>历史金钱999，库存99，地点旧城。</summary>".repeat(500)), ...fixture.messages], config, budget: 16000, world });
assert.equal(JSON.stringify(world), worldBefore);
assert.ok(JSON.stringify(withWorld.messages).includes("当前权威世界快照"));
assert.ok(JSON.stringify(withWorld.messages).includes('\\"'+record.template.initial.actorId+'\\":77'));
assert.ok(JSON.stringify(withWorld.messages).includes("硬状态以当前世界快照为准"));
check("权威快照覆盖旧摘要的硬状态含义，构建不修改世界");
for (const counter of [createTokenCounter("gpt-4o"), createTokenCounter("unknown")]) {
  const next = buildWorkingContext({ messages: fixture.messages, config, budget: 5000, measure: (messages) => measureContext(messages, counter).total });
  assert.ok(measureContext(next.messages, counter).total <= 5000);
  assert.ok(fixture.facts.every((f) => JSON.stringify(next.messages).includes(f)));
}
check("tokenizer 与字符/UTF-8 估算分别按各自单位满足预算");
const fixed = buildWorkingContext({ messages: [{ role: "system", content: "固定设定".repeat(1000), timestamp: 0 }, userMessage("不能删除的当前问题")], config, budget: 20 });
assert.equal(fixed.stats.overBudget, true); assert.ok(fixed.diagnostics.overBudgetReasons[0].includes("固定设定"));
assert.equal(fixed.messages.at(-1)?.content, "不能删除的当前问题");
check("固定区本身超预算说明原因，当前用户消息从不裁切");
const evidence = extractContextFacts([userMessage("我打算购买长剑。"), assistantMessage("她答应明日归还铜钱。")]);
assert.equal(evidence[0].kind, "intent"); assert.equal(evidence[1].kind, "promise");
check("用户意图与已叙述承诺标记分开，不自动升级为权威状态");
const root = path.resolve(import.meta.dirname, "../../../data/test-runs"); fs.mkdirSync(root, { recursive: true });
const run = fs.mkdtempSync(path.join(root, "context-builder-"));
fs.writeFileSync(path.join(run, "report.json"), JSON.stringify({ comparisons, counting: "characters", budget: 16000, checks, realProvider: "not_requested" }, null, 2));
console.log(JSON.stringify(comparisons, null, 2)); console.log(`${checks} 项通过；报告：${run}`);
