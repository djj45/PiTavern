import fs from 'node:fs';
import path from 'node:path';
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
const root = path.resolve(import.meta.dirname, '..');
const git = (...args) => execFileSync('git', args, { cwd: root, encoding: 'utf8' }).trim();
if (git('status', '--porcelain', '--untracked-files=normal')) throw new Error('请先提交全部源码，再构建发布包');
const revision = git('rev-parse', 'HEAD'), version = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8')).version;
if (!/^\d+\.\d+\.\d+(?:-[\w.]+)?$/.test(version)) throw new Error('版本号无效');
const names = git('ls-tree', '-r', '--name-only', revision).split('\n');
if (names.some((name) => /(^|\/)(data|node_modules|\.env|\.git)(\/|$)/.test(name))) throw new Error('已跟踪文件中包含私人资料或依赖目录，拒绝打包');
const outputRoot = path.join(root, 'data/releases'); fs.mkdirSync(outputRoot, { recursive: true });
const directory = fs.mkdtempSync(path.join(outputRoot, 'PiTavern-' + version + '-'));
const filename = 'PiTavern-' + version + '.tar.gz', archive = path.join(directory, filename);
execFileSync('git', ['archive', '--format=tar.gz', '--prefix=PiTavern-' + version + '/', '-o', archive, revision], { cwd: root });
const sha256 = createHash('sha256').update(fs.readFileSync(archive)).digest('hex');
fs.writeFileSync(path.join(directory, 'SHA256SUMS'), sha256 + '  ' + filename + '\n');
const manifest = { version, revision, archive, sha256, createdAt: new Date().toISOString(), type: 'source', includesPrivateData: false, node: '>=22.19', providerAcceptance: 'not_executed_by_packager', largeLibraryAcceptance: 'not_executed_by_packager' };
fs.writeFileSync(path.join(directory, 'manifest.json'), JSON.stringify(manifest, null, 2) + '\n');
console.log(JSON.stringify(manifest, null, 2));
